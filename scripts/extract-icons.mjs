/**
 * Extracts the supplied Tabler SVG icons we actually use into a TypeScript
 * module, so the reel ships real icon artwork rather than hand-drawn
 * lookalikes.
 *
 * Output: src/video/generated/tabler-icons.ts
 *
 * Usage: node scripts/extract-icons.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('pngs/tabler-icons-main/icons/outline');
const OUT = path.resolve('src/video/generated/tabler-icons.ts');

/** Icon names the reel references. Missing names are reported, never invented. */
const WANTED = [
  'robot',
  'brain',
  'message-chatbot',
  'message-2',
  'send',
  'code',
  'terminal-2',
  'browser',
  'world',
  'search',
  'mail',
  'mail-fast',
  'calendar-event',
  'calendar-check',
  'chart-bar',
  'file-text',
  'folder',
  'device-laptop',
  'device-desktop',
  'app-window',
  'layout-grid',
  'circle-check',
  'checks',
  'list-check',
  'cursor',
  'pointer',
  'mouse',
  'click',
  'keyboard',
  'cpu',
  'settings',
  'bolt',
  'plug',
  'database',
  'table',
  'clock',
  'refresh',
  'arrow-right',
  'arrow-narrow-right',
  'trending-up',
  'eye',
  'shield-check',
  'key',
  'stack-2',
  'affiliate',
  'binary-tree',
  'hierarchy-2',
  'target',
  'rocket',
  'sparkles',
  'photo',
  'player-play',
  'window-maximize',
  'checkbox',
  'adjustments',
  'puzzle',
];

const readAttr = (tag, name) => {
  const m = tag.match(new RegExp(name + '="([^"]*)"'));
  return m ? m[1] : null;
};

const missing = [];
const entries = [];

for (const name of WANTED) {
  const file = path.join(SRC, name + '.svg');
  if (!fs.existsSync(file)) {
    missing.push(name);
    continue;
  }
  const svg = fs.readFileSync(file, 'utf8').trim();
  const openIdx = svg.indexOf('<svg');
  const closeIdx = openIdx < 0 ? -1 : svg.indexOf('>', openIdx);
  if (openIdx < 0 || closeIdx < 0) {
    missing.push(name);
    continue;
  }
  const openTag = svg.slice(openIdx, closeIdx + 1);
  const viewBox = readAttr(openTag, 'viewBox') || '0 0 24 24';
  const endTag = svg.lastIndexOf('</svg>');
  const inner = svg.slice(closeIdx + 1, endTag).trim();
  if (!inner) {
    missing.push(name);
    continue;
  }

  entries.push(
    '  ' +
      JSON.stringify(name) +
      ': {\n    viewBox: ' +
      JSON.stringify(viewBox) +
      ',\n    body: ' +
      JSON.stringify(inner) +
      ',\n  },',
  );
}

const lines = [
  '// AUTO-GENERATED by scripts/extract-icons.mjs - do not edit by hand.',
  '// Source: pngs/tabler-icons-main (MIT, Tabler Icons).',
  '',
  'export type TablerIconName = keyof typeof ICONS;',
  '',
  'export const ICONS = {',
  entries.join('\n'),
  '} as const;',
  '',
];

fs.mkdirSync(path.dirname(OUT), {recursive: true});
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(entries.length + ' icons -> ' + path.relative(process.cwd(), OUT));
if (missing.length) console.log('missing (skipped): ' + missing.join(', '));
process.exit(entries.length > 0 ? 0 : 1);
